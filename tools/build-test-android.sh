#!/bin/sh
# Build the native-vs-JIT test programs for the device (bionic, no proot).
#
# android/test-bitops.sh builds them against the host's glibc, and a proot layer sits
# under that: signals and thread scheduling there are not the phone's. A SIGSEGV seen on
# the glibc host does not appear on bionic, so anything about timing, WFE or spinlocks
# has to be measured on the device.
#
#   tools/build-test-android.sh          # build
#   tools/build-test-android.sh --push   # build, push and run
set -eu
cd "$(dirname "$0")/.."

NDK=${ANDROID_NDK_HOME:-/home/he/Android/Sdk/ndk/29.0.14206865}
: "${API:=28}"
BIN=""
for t in linux-arm64 linux-x86_64; do
    if [ -x "$NDK/toolchains/llvm/prebuilt/$t/bin/clang" ]; then BIN="$NDK/toolchains/llvm/prebuilt/$t/bin"; break; fi
done
[ -n "$BIN" ] || { echo "no llvm under $NDK" >&2; exit 1; }
CC="$BIN/aarch64-linux-android$API-clang"
OUT=${OUT:-build/andcli-test}
rm -rf "$OUT/obj"
mkdir -p "$OUT/obj"

"$BIN/clang" --target=aarch64-linux-gnu -c tests/bitops_prog.s -o "$OUT/bitops_prog.o"
"$BIN/llvm-objcopy" -O binary --only-section=.text "$OUT/bitops_prog.o" "$OUT/bitops_prog.bin"

sym() { "$BIN/llvm-nm" --defined-only -S "$OUT/bitops_prog.o" | awk -v n="$1" '$4 == n { print $1, $2 }'; }
hdr="$OUT/bitops_prog_bytes.h"
echo "/* generated by tools/build-test-android.sh */" > "$hdr"
for pair in bitops_prog:BITOPS memops_prog:MEMOPS mathops_prog:MATHOPS atomics_prog:ATOMICS \
            sched_prog:SCHED sched_mc_waker:MCW sched_mc_waiter:MCT sched_mc_spin:MCS sched_evt:EVT; do
    name=${pair%%:*}; tag=${pair##*:}
    set -- $(sym "$name")
    [ -n "${1:-}" ] && printf '#define %s_OFF 0x%s\n#define %s_LEN 0x%s\n' "$tag" "$1" "$tag" "$2" >> "$hdr"
done
printf 'static const unsigned char prog_blob[] = {' >> "$hdr"
od -An -v -tu1 "$OUT/bitops_prog.bin" | tr -s ' ' | sed 's/^ //; s/ /,/g; s/$/,/' | tr -d '\n' >> "$hdr"
printf '};\nstatic const size_t prog_blob_len = sizeof prog_blob;\n' >> "$hdr"

INC="-Icore -Ihost -Idevices -Iandroid/compat/include -I$OUT"
DEFS="-D_GNU_SOURCE -D__ANDROID__ -include android/compat/include/hv_darwin_compat.h"
CFLAGS="-std=gnu11 -O1 -g -w $INC $DEFS"

# Only what the tests touch: the engine core, the JIT region, and compat for
# mach_absolute_time(). The installer's disk/USB/crypto stack is not involved.
for f in core/*.c host/jit_region.c android/compat/compat_android.c; do
    o="$OUT/obj/$(basename "$f" .c).o"
    if [ ! -f "$o" ] || [ "$f" -nt "$o" ]; then
        $CC $CFLAGS -c "$f" -o "$o"
    fi
done
if [ ! -f "$OUT/obj/host_enter.o" ] || [ host/enter.S -nt "$OUT/obj/host_enter.o" ]; then
    $CC -D_GNU_SOURCE -D__ANDROID__ -Ihost -Icore -c host/enter.S -o "$OUT/obj/host_enter.o"
fi
$CC $CFLAGS tests/test_bitops.c "$OUT"/obj/*.o -o "$OUT/test_bitops" -lm -latomic
echo "built $OUT/test_bitops"

if [ "${1:-}" = "--push" ]; then
    D=${DEVICE:-emulator-5554}
    adb -s "$D" push "$OUT/test_bitops" /data/local/tmp/henge/test_bitops >/dev/null
    adb -s "$D" shell 'chmod 755 /data/local/tmp/henge/test_bitops'
    shift
    adb -s "$D" shell "cd /data/local/tmp/henge && ./test_bitops $*"
fi
