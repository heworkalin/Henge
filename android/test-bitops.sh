#!/bin/sh
# Builds the engine for the host (aarch64 glibc) and runs the bit-operation differential test.
#
# tests/test_bitops.c runs one short program of bit and NEON operations twice — natively and
# through the JIT — and compares what it wrote. There is no device in the loop, so a round takes
# seconds; this is the tool for "is a single instruction translated wrongly".
#
#   ./android/test-bitops.sh
set -eu
cd "$(dirname "$0")/.."

# The host compiler and assembler. The NDK ships both, and the target below is the host's own
# architecture with the host's own libc, which is what makes the native half a real CPU run.
: "${NDK:=${ANDROID_NDK_HOME:-/home/he/Android/Sdk/ndk/29.0.14206865}}"
BIN=""
for t in linux-arm64 linux-x86_64; do
    if [ -x "$NDK/toolchains/llvm/prebuilt/$t/bin/clang" ]; then
        BIN="$NDK/toolchains/llvm/prebuilt/$t/bin"
        break
    fi
done
[ -n "$BIN" ] || { echo "test-bitops.sh: no llvm in $NDK" >&2; exit 1; }
: "${CC:=aarch64-linux-gnu-gcc}"

OUT=${OUT:-build/host-test}
mkdir -p "$OUT"

# The program under test: assembled here, so the test needs no assembler at run time.
"$BIN/clang" --target=aarch64-linux-gnu -c tests/bitops_prog.s -o "$OUT/bitops_prog.o"
"$BIN/llvm-objcopy" -O binary --only-section=.text "$OUT/bitops_prog.o" "$OUT/bitops_prog.bin"
# The two programs are in one .text; nm says where each starts and ends.
sym() { "$BIN/llvm-nm" --defined-only -S "$OUT/bitops_prog.o" | awk -v n="$1" '$4 == n { print $1, $2 }'; }
read -r BITOPS_OFF BITOPS_SIZE <<EOF
$(sym bitops_prog)
EOF
read -r MEMOPS_OFF MEMOPS_SIZE <<EOF
$(sym memops_prog)
EOF
{
    echo "/* generated by android/test-bitops.sh */"
    printf '#define BITOPS_OFF 0x%s\n' "$BITOPS_OFF"
    printf '#define BITOPS_LEN 0x%s\n' "$BITOPS_SIZE"
    printf '#define MEMOPS_OFF 0x%s\n' "$MEMOPS_OFF"
    printf '#define MEMOPS_LEN 0x%s\n' "$MEMOPS_SIZE"
    printf 'static const unsigned char prog_blob[] = {'
    od -An -v -tu1 "$OUT/bitops_prog.bin" | tr -s ' ' | sed 's/^ //; s/ /,/g; s/$/,/'
    printf '};\n'
    printf 'static const size_t prog_blob_len = sizeof prog_blob;\n'
} > "$OUT/bitops_prog_bytes.h"

INC="-Icore -Ihost -Idevices -Iandroid/compat/include -I$OUT"
DEFS="-D_GNU_SOURCE -D__ANDROID__ -include android/compat/include/hv_darwin_compat.h"
CFLAGS="-std=gnu11 -O1 -g -w $INC $DEFS"

cat > "$OUT/tid.c" <<'EOF'
#include <pthread.h>
int pthread_gettid_np(pthread_t t) { (void)t; return 0; }
EOF

for f in core/*.c host/jit_region.c android/compat/compat_android.c; do
    o="$OUT/$(basename "$f" .c).o"
    [ -f "$o" ] && [ "$o" -nt "$f" ] || $CC $CFLAGS -c "$f" -o "$o"
done
[ -f "$OUT/enter.o" ] || $CC -c host/enter.S -o "$OUT/enter.o"
[ -f "$OUT/tid.o" ] || $CC $CFLAGS -c "$OUT/tid.c" -o "$OUT/tid.o"

$CC $CFLAGS tests/test_bitops.c "$OUT"/*.o -o "$OUT/test_bitops" -lpthread -lm -latomic
exec "$OUT/test_bitops"
